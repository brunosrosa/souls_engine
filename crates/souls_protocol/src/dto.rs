/// Model execution tier classification for the Zero-Trust cascade.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum ModelTier {
    /// Nuvem de ponta (ex: Claude 3.5 Sonnet, DeepSeek V3) para tarefas reflexivas.
    PremiumCloud,
    /// Nuvem rápida e econômica (ex: Gemini Flash, Haiku) para triagem e síntese leve.
    FlashCloud,
    /// Silício local bare-metal (RTX 2060m / CPU Intel AVX2) com custo zero.
    LocalGPU,
}

/// Routing tier identifiers for the ParetoBandit decision engine.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum RoutingTier {
    /// Nível 0: Local Velocista (LFM 1.2B / ONNX / ModernBERT). Custo $0.
    Tier0,
    /// Nível 1: Local Trator (Nemotron 4B / Qwen Coder na dGPU). Custo $0.
    Tier1,
    /// Nível 2: Nuvem Premium (DeepSeek / Claude). Custo por token.
    Tier2,
}

/// Routing determination generated by IronCostBreaker.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum AllowedRoute {
    /// Rota original aprovada para o tier indicado.
    OriginalRoute(ModelTier),
    /// Orçamento esgotado mas payload suportado pela VRAM local: fallback gracioso.
    FallbackToLocal,
    /// Bloqueio total: orçamento excedido e payload incompatível com a VRAM.
    Blocked,
}

/// Multidimensional efficiency, economics, and execution metrics ($E^3$).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct FinOpsCostMetrics {
    pub prefill_tokens: u64,
    pub generation_tokens: u64,
    pub total_tokens: u64,
    pub latency_ms: f64,
    pub cost_usd: f64,
    pub quality_score: Option<f32>,
    pub e3_score: f64,
    pub deviation_ratio: Option<f32>,
}

/// Normalized $E^3$ score breakdown.
///
/// Composites efficiency (latency/throughput), economics (cost per quality unit),
/// and execution (accuracy/compliance) into an aggregated utility score.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct E3EfficiencyScore {
    pub efficiency: f64,
    pub economics: f64,
    pub execution: f64,
    pub composite_score: f64,
}

impl E3EfficiencyScore {
    #[must_use]
    pub fn new(efficiency: f64, economics: f64, execution: f64) -> Self {
        // Weighted average: 40% execution, 35% economics, 25% efficiency
        let composite_score = (execution * 0.40) + (economics * 0.35) + (efficiency * 0.25);
        Self {
            efficiency,
            economics,
            execution,
            composite_score,
        }
    }
}

