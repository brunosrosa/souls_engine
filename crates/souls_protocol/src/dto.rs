#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_e3_score_calculation() {
        let score = E3EfficiencyScore::new(1.0, 1.0, 1.0);
        assert!((score.composite_score - 1.0).abs() < 1e-6);

        let partial = E3EfficiencyScore::new(0.5, 0.8, 0.9);
        // composite = 0.9*0.40 + 0.8*0.35 + 0.5*0.25 = 0.36 + 0.28 + 0.125 = 0.765
        assert!((partial.composite_score - 0.765).abs() < 1e-6);
    }

    #[test]
    fn test_hardware_constants_sanity() {
        assert!(RTX_2060M_WDDM_CEILING_MB < RTX_2060M_VRAM_TOTAL_MB);
        assert_eq!(RTX_2060M_VRAM_TOTAL_MB, 6144);
        assert_eq!(MIN_PCIE_BANDWIDTH_GBPS_FOR_SPILLOVER, 32.0);
    }
}
